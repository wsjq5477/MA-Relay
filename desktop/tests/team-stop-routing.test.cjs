const test=require('node:test'),assert=require('node:assert/strict');
const {graphFixture}=require('./i06b-ui-fixture.cjs');
test('production Coordinator and AgentNetwork route a team cancel to the exact original machine/task and reconcile the original receipt',async t=>{
 const f=await graphFixture({nativeExecution:true,loseCancelAck:true});t.after(()=>f.close());
 let op=0;const call=async(method,p={})=>{const r=await f.call('team.'+method,{operationId:'routing-'+ ++op,...p});assert(r.ok,JSON.stringify(r.error));return r.result;};
 const n=f.nodes.find(n=>n.adapter==='claude');
 const a=await call('registerAgent',{kind:'native',nodeId:n.nodeId,name:'native',purpose:'coordinate'});
 const team=await call('createTeam',{name:'routing',leaderId:a.agentId,memberIds:[a.agentId]});
 const run=await call('createRun',{teamId:team.teamId,name:'routing work',goal:'original routing',acceptance:'terminal only'});
 const attempt=await call('execute',{runId:run.runId,agentId:a.agentId,message:'original controlled task'});
 assert.equal(attempt.state,'running');assert.deepEqual(attempt.waiting,{kind:'permission',requestCount:1});
 await call('stopRun',{runId:run.runId,expectedRevision:run.revision});
 const original=f.hosts.get(n.machineId),cancel=original.calls.filter(c=>c.method==='ipc'&&c.p.op==='cancel');
 assert.equal(cancel.length,1);assert.equal(n.machineId+'::'+cancel[0].p.taskId,attempt.taskId);
 assert.equal([...f.hosts.values()].filter(h=>h!==original).flatMap(h=>h.calls).filter(c=>c.p.op==='cancel').length,0);
 const fs=require('node:fs'),path=require('node:path');
 const readJournal=()=>JSON.parse(fs.readFileSync(path.join(f.directory,'pending.json'),'utf8'));
 original.controls.clear();
 let context=await call('refresh',{runId:run.runId});assert.equal(context.attempts[0].stop.state,'unknown');
 assert.equal(readJournal().find(r=>r.id===cancel[0].p.operationId).state,'unknown');
 original.controls.set(cancel[0].p.operationId,{operationId:cancel[0].p.operationId,state:'confirmed'});
 context=await call('refresh',{runId:run.runId});assert.equal(context.run.state,'stopping');assert.equal(context.attempts[0].stop.state,'confirmed');
 assert(original.calls.some(c=>c.p.op==='operation'&&c.p.operationId===cancel[0].p.operationId));
 original.tasks[0].status='succeeded';delete original.tasks[0].waiting;
 context=await call('refresh',{runId:run.runId});assert.equal(context.run.state,'closed');assert.equal(context.attempts[0].state,'succeeded');
 assert.equal(original.calls.filter(c=>c.p.op==='cancel').length,1);
 const journal=readJournal();
 assert.equal(journal.find(r=>r.id===cancel[0].p.operationId).state,'confirmed');
});
